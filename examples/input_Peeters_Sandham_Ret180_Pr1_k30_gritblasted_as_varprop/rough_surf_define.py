lmap     =  lambda f,x: list(map(f,x))
MATH_PI  =  float(np.pi)

# ------------------------------------------------------------------------
#                  Height Function
# ------------------------------------------------------------------------

class Height_Function:
    def __init__(self):
        
        self.Lx       =  5.63
        self.Ly       =  2
        self.Lz       =  2.815
        self.nreps_x  =  1
        self.nreps_z  =  1

        self._mnab  =  [lmap(float,line.split()) for line in text_mnab_rough_surf.split('\n') if line]

    def get_h(self, x, z, side = None, lib = np):
        assert (type(side) == str) and (side in ['bottom', 'top'])
        #
        # Please note that, due to body-force diagram constraints,
        #    To achieve a friction_velocity=1 for Ly=2 in the channel flow:
        #        - The average height of the bottom surface should be zero,
        #          and the average height of the top surface should be Ly=2.
        #    This helps to achieve U=U+, T=T+ in the simulation.
        #    Otherwise, everything still works, but U.ne.(U+)
        #    (The Fourier series below has a zero first component, so it works right away)
        #
        H = 0.
        for m,n,a,b in self._mnab:
            theta   =  2*MATH_PI * (m*x/self.Lx + n*z/self.Lz)
            H      +=  a*lib.cos(theta) + b*lib.sin(theta)
        
        if side == 'top':
            H = self.Ly - H
        
        return H

