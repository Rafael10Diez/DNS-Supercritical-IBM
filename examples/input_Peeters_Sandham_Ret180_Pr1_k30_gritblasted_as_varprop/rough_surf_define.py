#                  Plotter
# ------------------------------------------------------------------------

def Quick_Plot(surf):
    import  numpy                           as  np
    from    os.path            import join  as  pjoin
    import  matplotlib.pyplot               as  plt 
    from    os.path            import dirname, abspath

    nz      =  400
    nx      =  round(nz * surf.Lx / surf.Lz)
    xu      =  np.linspace(0,surf.Lx, nx+1).reshape(-1, 1)
    zu      =  np.linspace(0,surf.Lz, nz+1).reshape( 1,-1)
    yu      =  surf.get_h(xu,zu,'bottom',np)
    mk_p    =  lambda x: (x.reshape(-1)[:-1] + 0.5*np.diff(x.reshape(-1))).reshape(*[(-1 if s>1 else s) for s in x.shape])
    xp      =  mk_p(xu).reshape(-1, 1)
    zp      =  mk_p(zu).reshape( 1,-1)
    yp      =  surf.get_h(xp,zp,'bottom',np)
    def myplot():
        zeros  =  np.zeros_like(xu + zu)
        for masking in [0,1]:
            yy = yp.copy()
            if masking:
                yy[abs(yy)> 1e-6] = np.sign(yy[abs(yy)> 1e-6])
                vmin, vmax        = -1, 1
            else:
                vmax  =  max(np.fabs(yy.max()), np.fabs(yy.min()))
                vmin  =  -vmax
            plot_fname  =  pjoin(dirname(abspath(__file__)), f'img_surf_mask_{int(masking)}.png')
            fig,ax = plt.subplots()
            im = ax.pcolormesh((xu+zeros).transpose(),(zu+zeros).transpose(),yy.transpose() , cmap = 'gist_gray', vmin = vmin, vmax = vmax)
            fig.colorbar(im, ax=ax,fraction=0.02, pad=0.04)
            ax.set_aspect('equal', adjustable='box')
            ax.set_title('Height Function' + (' (sign) (1: positive, -1: negative)' if masking else ' (y = f(x,z))'))
            ax.set_xlabel('x')
            ax.set_ylabel('z')
            fig.tight_layout()
            AR = np.array(fig.get_size_inches())
            fig.set_size_inches(AR*6/AR[0])
            fig.savefig(  plot_fname                                 ,
                          bbox_inches  =  'tight'                    ,
                          format       =  plot_fname.split('.')[-1]  ,
                          dpi          =  8*fig.dpi                  ,
                          pad_inches   =  0.1                        )
            plt.close(fig)
    myplot()

    xu          =  xu + np.zeros_like(xu+zu)
    zu          =  zu + np.zeros_like(xu+zu)
    
    dhdx        =  np.diff(yu,axis=0)/np.diff(xu,axis=0)
    dhdz        =  np.diff(yu,axis=1)/np.diff(zu,axis=1)
    sx,sz       =  [min(a,b) for a,b in zip(dhdx.shape, dhdz.shape)]
    dhdx, dhdz  =  dhdx[:sx,:sz], dhdz[:sx,:sz]
    max_angle   =  np.fabs(np.arccos(1/np.sqrt(1 + dhdx**2 + dhdz**2))*180/np.pi).max()

    avg_height  =  np.average(yp)
    y_min       =  min(yu.min(), yp.min())
    y_max       =  max(yu.max(), yp.max())
    Lx      = surf.Lx     
    Lz      = surf.Lz     
    Ly      = surf.Ly     
    nreps_x = surf.nreps_x
    nreps_z = surf.nreps_z
    print('\n---------------------- Surface Statistics ----------------------')
    print(f"\n    Main parameters: ")
    print(f"        {__file__   = }")
    print(f"        {Lx         = :10.3f}")
    print(f"        {Lz         = :10.3f}")
    print(f"        {Ly         = :10.3f}")
    print(f"        {nreps_x    = :10d}")
    print(f"        {nreps_z    = :10d}")
    print(f"\n    Sampled quantities (image with {nx} x {nz} points in the x-z directions) (created only for plotting)")
    print(f"        {max_angle  = :10.3f} degrees")
    print(f"        {avg_height = :10.3e}")
    print(f"        {y_min      = :10.3e}")
    print(f"        {y_max      = :10.3e}\n")

